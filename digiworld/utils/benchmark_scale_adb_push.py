"""
Benchmark: ADB Push at Scale — 1K / 2K / 5K / 10K / 50K / 100K Files
======================================================================
Reads scale tiers from utils/scale_test_assets/ (generated by
generate_scale_assets.py) and times parallel `adb push` for each tier
using 5, 8, and 12 workers.

Tiers whose total size exceeds the emulator's free sdcard space are
automatically skipped with a clear warning.

Usage:
    python3 benchmark_scale_adb_push.py
    python3 benchmark_scale_adb_push.py --runs 2 --workers 8 12
    python3 benchmark_scale_adb_push.py --max-tier-mb 400
"""

import argparse
import statistics
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Optional, Tuple

sys.stdout.reconfigure(line_buffering=True)

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

SCRIPT_DIR   = Path(__file__).parent
ASSETS_DIR   = SCRIPT_DIR / "scale_test_assets"
DEVICE_BASE  = "/sdcard/andojo_scale_benchmark"

WORKER_COUNTS   = [5, 8, 12]
DEFAULT_RUNS    = 2
DEFAULT_MAX_MB  = 600   # skip tiers whose total size exceeds this (emulator guard)


# ---------------------------------------------------------------------------
# Data classes
# ---------------------------------------------------------------------------

@dataclass
class RunResult:
    workers:      int
    elapsed_sec:  float
    files_pushed: int
    bytes_pushed: int

    @property
    def mb_per_sec(self) -> float:
        return (self.bytes_pushed / 1_048_576) / self.elapsed_sec if self.elapsed_sec > 0 else 0.0

    @property
    def files_per_sec(self) -> float:
        return self.files_pushed / self.elapsed_sec if self.elapsed_sec > 0 else 0.0


@dataclass
class TierBenchmark:
    name:        str            # e.g. "tier_5k"
    assets_path: Path
    file_count:  int
    byte_count:  int
    results:     List[RunResult] = field(default_factory=list)

    @property
    def size_mb(self) -> float:
        return self.byte_count / 1_048_576

    def results_for(self, workers: int) -> List[RunResult]:
        return [r for r in self.results if r.workers == workers]

    def mean_sec(self, workers: int) -> Optional[float]:
        rs = self.results_for(workers)
        return statistics.mean(r.elapsed_sec for r in rs) if rs else None

    def fastest_workers(self, worker_counts: List[int]) -> int:
        best_w, best_t = worker_counts[0], float("inf")
        for w in worker_counts:
            t = self.mean_sec(w)
            if t is not None and t < best_t:
                best_t, best_w = t, w
        return best_w


# ---------------------------------------------------------------------------
# Discovery
# ---------------------------------------------------------------------------

def _sort_key(d: Path) -> int:
    """Sort tier_Xk directories numerically by X."""
    name = d.name  # "tier_1k", "tier_10k", …
    try:
        num = name.replace("tier_", "").rstrip("k")
        return int(num)
    except ValueError:
        return 0


def discover_tiers(assets_dir: Path, max_mb: float) -> Tuple[List[TierBenchmark], List[str]]:
    if not assets_dir.exists():
        sys.exit(
            f"[ERROR] Scale assets not found at {assets_dir}\n"
            "        Run:  python3 generate_scale_assets.py"
        )

    tiers: List[TierBenchmark] = []
    skipped: List[str] = []

    for td in sorted(assets_dir.iterdir(), key=_sort_key):
        if not td.is_dir():
            continue
        files = [p for p in td.rglob("*") if p.is_file()]
        if not files:
            continue
        total_bytes = sum(f.stat().st_size for f in files)
        total_mb    = total_bytes / 1_048_576

        if max_mb > 0 and total_mb > max_mb:
            msg = f"{td.name}  ({len(files):,} files / {total_mb:.0f} MB) — exceeds --max-tier-mb {max_mb:.0f}"
            skipped.append(msg)
            continue

        tiers.append(TierBenchmark(
            name=td.name,
            assets_path=td,
            file_count=len(files),
            byte_count=total_bytes,
        ))

    return tiers, skipped


# ---------------------------------------------------------------------------
# ADB helpers
# ---------------------------------------------------------------------------

def adb_run(*args, device: str, timeout: int = 120) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["adb", "-s", device] + list(args),
        capture_output=True, text=True, timeout=timeout,
    )


def remote_mkdir(path: str, device: str) -> None:
    adb_run("shell", f"mkdir -p '{path}'", device=device)


def remote_rmdir(path: str, device: str) -> None:
    subprocess.run(
        ["adb", "-s", device, "shell", f"rm -r '{path}' 2>/dev/null; true"],
        capture_output=True, timeout=120,
    )


def push_file(args: Tuple[Path, str, str]) -> Tuple[bool, int]:
    local, remote, device = args
    try:
        r = subprocess.run(
            ["adb", "-s", device, "push", str(local), remote],
            capture_output=True, timeout=60,
        )
        return r.returncode == 0, local.stat().st_size
    except Exception:
        return False, 0


# ---------------------------------------------------------------------------
# Timed push
# ---------------------------------------------------------------------------

def timed_push(
    files:       List[Path],
    assets_path: Path,
    remote_base: str,
    workers:     int,
    device:      str,
) -> RunResult:
    tasks = [
        (f, f"{remote_base}/{f.relative_to(assets_path)}".replace("\\", "/"), device)
        for f in files
    ]
    total_bytes = 0
    t0 = time.perf_counter()
    with ThreadPoolExecutor(max_workers=workers) as pool:
        for ok, nb in pool.map(push_file, tasks):
            if ok:
                total_bytes += nb
    elapsed = time.perf_counter() - t0
    return RunResult(
        workers=workers,
        elapsed_sec=elapsed,
        files_pushed=len(tasks),
        bytes_pushed=total_bytes,
    )


# ---------------------------------------------------------------------------
# Benchmark runner
# ---------------------------------------------------------------------------

def run_benchmarks(
    tiers:         List[TierBenchmark],
    worker_counts: List[int],
    runs:          int,
    device:        str,
) -> None:
    for i, tier in enumerate(tiers, 1):
        print(f"\n{'═'*60}")
        print(f"  [{i}/{len(tiers)}]  {tier.name}  —  {tier.file_count:,} files  {tier.size_mb:.1f} MB")
        print(f"{'═'*60}")

        files       = [p for p in tier.assets_path.rglob("*") if p.is_file()]
        remote_base = f"{DEVICE_BASE}/{tier.name}"

        # Create remote directory tree once
        subdirs = sorted({f.parent for f in files})
        for sub in subdirs:
            rel = sub.relative_to(tier.assets_path)
            remote_mkdir(f"{remote_base}/{rel}".rstrip("/."), device)

        for workers in worker_counts:
            for run_idx in range(1, runs + 1):
                result = timed_push(files, tier.assets_path, remote_base, workers, device)
                tier.results.append(result)
                print(
                    f"    {workers:>2}w  run {run_idx}/{runs}"
                    f"  {result.elapsed_sec:7.2f}s"
                    f"  {result.mb_per_sec:5.1f} MB/s"
                    f"  {result.files_per_sec:6.0f} files/s"
                )

        remote_rmdir(remote_base, device)

    remote_rmdir(DEVICE_BASE, device)


# ---------------------------------------------------------------------------
# Report
# ---------------------------------------------------------------------------

def _fmt(v: Optional[float], d: int = 3) -> str:
    return f"{v:.{d}f}" if v is not None else "—"


def generate_report(
    tiers:         List[TierBenchmark],
    skipped:       List[str],
    worker_counts: List[int],
    runs:          int,
    device:        str,
    max_mb:        float,
) -> str:
    now   = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    L: List[str] = []

    total_files = sum(t.file_count for t in tiers)
    total_mb    = sum(t.size_mb    for t in tiers)

    L += [
        "# ADB Push Scale Benchmark Report",
        f"## Scale Tiers: {', '.join(t.name for t in tiers)}",
        "",
        f"> **Generated:** {now}  ",
        f"> **Device:** `{device}`  ",
        f"> **Worker counts:** {', '.join(str(w) for w in worker_counts)}  ",
        f"> **Runs per config:** {runs}  ",
        f"> **Tiers tested:** {len(tiers)}  ",
        f"> **Total files (all tiers):** {total_files:,}  ({total_mb:.1f} MB)  ",
        f"> **Max tier size (emulator guard):** {max_mb:.0f} MB  ",
    ]

    if skipped:
        L.append("> **Skipped (exceeded emulator space):** " + ", ".join(skipped) + "  ")

    L += [
        "",
        "---",
        "",
        "## Summary by Tier",
        "",
        "| Tier | Files | Size (MB) | "
        + " | ".join(f"{w}w Mean (s)" for w in worker_counts)
        + " | Best |",
        "|---|---:|---:|"
        + "|".join("---:" for _ in worker_counts)
        + "|:---:|",
    ]

    win_count: Dict[int, int] = {w: 0 for w in worker_counts}
    for tier in tiers:
        best_w = tier.fastest_workers(worker_counts)
        win_count[best_w] += 1
        times = [_fmt(tier.mean_sec(w)) for w in worker_counts]
        L.append(
            f"| `{tier.name}` | {tier.file_count:,} | {tier.size_mb:.1f} | "
            + " | ".join(times)
            + f" | **{best_w}w** |"
        )

    L += ["", "---", "", "## Raw Runs", ""]
    L += [
        "| Tier | Workers | Run | Elapsed (s) | MB/s | Files/s |",
        "|---|:---:|:---:|---:|---:|---:|",
    ]
    for tier in tiers:
        run_no: Dict[int, int] = {w: 0 for w in worker_counts}
        for r in tier.results:
            run_no[r.workers] += 1
            L.append(
                f"| `{tier.name}` | {r.workers} | {run_no[r.workers]} | "
                f"{_fmt(r.elapsed_sec)} | {r.mb_per_sec:.2f} | {r.files_per_sec:.0f} |"
            )

    # Inference
    all_times: Dict[int, List[float]] = {w: [] for w in worker_counts}
    all_mbps:  Dict[int, List[float]] = {w: [] for w in worker_counts}
    for tier in tiers:
        for w in worker_counts:
            for r in tier.results_for(w):
                all_times[w].append(r.elapsed_sec)
                all_mbps[w].append(r.mb_per_sec)

    total_tested = sum(win_count.values())
    overall_best = max(worker_counts, key=lambda w: win_count[w])

    L += [
        "",
        "---",
        "",
        "## Inference",
        "",
        "### Win Rate",
        "",
        "| Workers | Tiers Won | Win % | Mean MB/s | Mean Time (s) |",
        "|:---:|---:|---:|---:|---:|",
    ]
    for w in worker_counts:
        pct    = win_count[w] / total_tested * 100 if total_tested else 0
        mbps   = statistics.mean(all_mbps[w])  if all_mbps[w]  else 0
        mean_t = statistics.mean(all_times[w]) if all_times[w] else 0
        L.append(
            f"| **{w}w** | {win_count[w]}/{total_tested} "
            f"| {pct:.0f}% | {mbps:.2f} | {mean_t:.2f} |"
        )

    L += [
        "",
        "### Scaling Behaviour",
        "",
        "| Tier | Files | "
        + " | ".join(f"{w}w (s)" for w in worker_counts)
        + " | Files/s (best) |",
        "|---|---:|"
        + "|".join("---:" for _ in worker_counts)
        + "|---:|",
    ]
    for tier in tiers:
        best_w = tier.fastest_workers(worker_counts)
        best_r = tier.results_for(best_w)
        fps    = statistics.mean(r.files_per_sec for r in best_r) if best_r else 0
        times  = [_fmt(tier.mean_sec(w)) for w in worker_counts]
        L.append(
            f"| `{tier.name}` | {tier.file_count:,} | "
            + " | ".join(times)
            + f" | {fps:.0f} |"
        )

    L += [
        "",
        "---",
        "",
        f"_Report generated by `digiworld/utils/benchmark_scale_adb_push.py`  "
        f"·  seed assets from `digiworld/utils/scale_test_assets/`_",
    ]

    return "\n".join(L)


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

def main() -> int:
    parser = argparse.ArgumentParser(
        description="Benchmark ADB push at scale (1K–100K files)."
    )
    parser.add_argument(
        "--output", default=str(SCRIPT_DIR / "adb_push_benchmark_report.md"),
        help="Destination Markdown file (default: adb_push_benchmark_report.md)",
    )
    parser.add_argument("--runs",    type=int, default=DEFAULT_RUNS)
    parser.add_argument("--workers", nargs="+", type=int, default=WORKER_COUNTS)
    parser.add_argument("--device",  default=None)
    parser.add_argument(
        "--max-tier-mb", type=float, default=DEFAULT_MAX_MB,
        help=(
            f"Skip tiers whose total size exceeds this (MB). "
            f"Prevents filling emulator sdcard. Default: {DEFAULT_MAX_MB}. "
            "Use 0 to disable."
        ),
    )
    args = parser.parse_args()

    worker_counts = sorted(set(args.workers))
    runs          = max(1, args.runs)

    result = subprocess.run(["adb", "devices"], capture_output=True, text=True)
    serials = [l.split("\t")[0] for l in result.stdout.splitlines() if "\tdevice" in l]
    if not serials:
        print("[ERROR] No ADB device connected. Run `adb devices` to check.")
        return 1
    device = args.device if args.device in serials else serials[0]

    print("=" * 60)
    print("  ADB Push Scale Benchmark")
    print("=" * 60)
    print(f"  Device      : {device}")
    print(f"  Assets dir  : {ASSETS_DIR}")
    print(f"  Max tier MB : {args.max_tier_mb}")
    print(f"  Workers     : {worker_counts}")
    print(f"  Runs        : {runs}")
    print(f"  Report      : {args.output}")
    print("=" * 60)

    tiers, skipped = discover_tiers(ASSETS_DIR, args.max_tier_mb)

    if skipped:
        print(f"\n  Skipping {len(skipped)} tier(s) (exceed emulator space):")
        for s in skipped:
            print(f"    · {s}")

    if not tiers:
        print("[ERROR] No tiers to benchmark. Lower --max-tier-mb or run generate_scale_assets.py.")
        return 1

    total_files = sum(t.file_count for t in tiers)
    total_ops   = len(tiers) * len(worker_counts) * runs
    print(f"\n  Tiers  : {len(tiers)}  ({', '.join(t.name for t in tiers)})")
    print(f"  Files  : {total_files:,}  |  Total push ops: {total_ops}")
    est_min = sum(t.file_count for t in tiers) * 0.06 * len(worker_counts) * runs / 60
    print(f"  Est.   : ~{est_min:.0f} min")

    adb_run("shell", f"mkdir -p '{DEVICE_BASE}'", device=device)
    run_benchmarks(tiers, worker_counts, runs, device)

    report = generate_report(tiers, skipped, worker_counts, runs, device, args.max_tier_mb)
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(report, encoding="utf-8")

    print(f"\n{'='*60}")
    print(f"  Report saved → {out}")
    print(f"{'='*60}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
