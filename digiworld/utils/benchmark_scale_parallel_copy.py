"""
Benchmark: Parallel File Copy at Scale — 1K / 2K / 5K / 10K / 50K / 100K
==========================================================================
Reads scale tiers from utils/scale_test_assets/ (generated by
generate_scale_assets.py) and benchmarks local parallel copy using
5, 8, and 12 workers.  No emulator required.

Usage:
    python3 benchmark_scale_parallel_copy.py
    python3 benchmark_scale_parallel_copy.py --runs 3 --workers 5 8 12
    python3 benchmark_scale_parallel_copy.py --output /tmp/report.md
"""

import argparse
import shutil
import statistics
import sys
import tempfile
import time
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Optional, Tuple

sys.stdout.reconfigure(line_buffering=True)

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

SCRIPT_DIR  = Path(__file__).parent
ASSETS_DIR  = SCRIPT_DIR / "scale_test_assets"

WORKER_COUNTS = [5, 8, 12]
DEFAULT_RUNS  = 2


# ---------------------------------------------------------------------------
# Data classes
# ---------------------------------------------------------------------------

@dataclass
class RunResult:
    workers:      int
    elapsed_sec:  float
    files_copied: int
    bytes_copied: int

    @property
    def mb_per_sec(self) -> float:
        return (self.bytes_copied / 1_048_576) / self.elapsed_sec if self.elapsed_sec > 0 else 0.0

    @property
    def files_per_sec(self) -> float:
        return self.files_copied / self.elapsed_sec if self.elapsed_sec > 0 else 0.0


@dataclass
class TierBenchmark:
    name:        str
    assets_path: Path
    file_count:  int
    byte_count:  int
    results:     List[RunResult] = field(default_factory=list)

    @property
    def size_mb(self) -> float:
        return self.byte_count / 1_048_576

    def results_for(self, workers: int) -> List[RunResult]:
        return [r for r in self.results if r.workers == workers]

    def mean_sec(self, workers: int) -> Optional[float]:
        rs = self.results_for(workers)
        return statistics.mean(r.elapsed_sec for r in rs) if rs else None

    def fastest_workers(self, worker_counts: List[int]) -> int:
        best_w, best_t = worker_counts[0], float("inf")
        for w in worker_counts:
            t = self.mean_sec(w)
            if t is not None and t < best_t:
                best_t, best_w = t, w
        return best_w


# ---------------------------------------------------------------------------
# Discovery
# ---------------------------------------------------------------------------

def _sort_key(d: Path) -> int:
    try:
        return int(d.name.replace("tier_", "").rstrip("k"))
    except ValueError:
        return 0


def discover_tiers(assets_dir: Path) -> List[TierBenchmark]:
    if not assets_dir.exists():
        sys.exit(
            f"[ERROR] Scale assets not found at {assets_dir}\n"
            "        Run:  python3 generate_scale_assets.py"
        )
    tiers: List[TierBenchmark] = []
    for td in sorted(assets_dir.iterdir(), key=_sort_key):
        if not td.is_dir():
            continue
        files = [p for p in td.rglob("*") if p.is_file()]
        if not files:
            continue
        tiers.append(TierBenchmark(
            name=td.name,
            assets_path=td,
            file_count=len(files),
            byte_count=sum(f.stat().st_size for f in files),
        ))
    return tiers


# ---------------------------------------------------------------------------
# Copy logic
# ---------------------------------------------------------------------------

def _copy_one(args: Tuple[Path, Path, Path]) -> int:
    src_file, src_root, dst_root = args
    rel = src_file.relative_to(src_root)
    dst = dst_root / rel
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src_file, dst)
    return src_file.stat().st_size


def parallel_copy(src: Path, workers: int, files: List[Path]) -> Tuple[float, int]:
    with tempfile.TemporaryDirectory() as tmp:
        dst = Path(tmp) / "dst"
        dst.mkdir()
        tasks = [(f, src, dst) for f in files]
        t0 = time.perf_counter()
        total_bytes = 0
        with ThreadPoolExecutor(max_workers=workers) as pool:
            for nb in pool.map(lambda t: _copy_one(t), tasks):
                total_bytes += nb
        return time.perf_counter() - t0, total_bytes


# ---------------------------------------------------------------------------
# Benchmark runner
# ---------------------------------------------------------------------------

def run_benchmarks(
    tiers:         List[TierBenchmark],
    worker_counts: List[int],
    runs:          int,
) -> None:
    for i, tier in enumerate(tiers, 1):
        files = [p for p in tier.assets_path.rglob("*") if p.is_file()]
        print(f"\n  [{i}/{len(tiers)}]  {tier.name}  —  {tier.file_count:,} files  {tier.size_mb:.1f} MB")

        for workers in worker_counts:
            elapsed_list: List[float] = []
            last_bytes = 0

            for run_idx in range(1, runs + 1):
                elapsed, nb = parallel_copy(tier.assets_path, workers, files)
                elapsed_list.append(elapsed)
                last_bytes = nb
                print(
                    f"      {workers:>2}w  run {run_idx}/{runs}"
                    f"  {elapsed:7.3f}s"
                    f"  {(nb / 1_048_576) / elapsed if elapsed else 0:5.1f} MB/s"
                )

            mean_t = statistics.mean(elapsed_list)
            tier.results.append(RunResult(
                workers=workers,
                elapsed_sec=mean_t,
                files_copied=tier.file_count,
                bytes_copied=last_bytes,
            ))


# ---------------------------------------------------------------------------
# Report
# ---------------------------------------------------------------------------

def _fmt(v: Optional[float], d: int = 3) -> str:
    return f"{v:.{d}f}" if v is not None else "—"


def generate_report(
    tiers:         List[TierBenchmark],
    worker_counts: List[int],
    runs:          int,
) -> str:
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    L: List[str] = []

    total_files = sum(t.file_count for t in tiers)
    total_mb    = sum(t.size_mb    for t in tiers)

    L += [
        "# Parallel File Copy Scale Benchmark Report",
        f"## Scale Tiers: {', '.join(t.name for t in tiers)}",
        "",
        f"> **Generated:** {now}  ",
        f"> **Worker counts:** {', '.join(str(w) for w in worker_counts)}  ",
        f"> **Runs per config:** {runs}  ",
        f"> **Tiers tested:** {len(tiers)}  ",
        f"> **Total files (all tiers):** {total_files:,}  ({total_mb:.1f} MB)  ",
        "",
        "---",
        "",
        "## Summary by Tier",
        "",
        "| Tier | Files | Size (MB) | "
        + " | ".join(f"{w}w Mean (s)" for w in worker_counts)
        + " | Best |",
        "|---|---:|---:|"
        + "|".join("---:" for _ in worker_counts)
        + "|:---:|",
    ]

    win_count: Dict[int, int] = {w: 0 for w in worker_counts}
    for tier in tiers:
        best_w = tier.fastest_workers(worker_counts)
        win_count[best_w] += 1
        times = [_fmt(tier.mean_sec(w)) for w in worker_counts]
        L.append(
            f"| `{tier.name}` | {tier.file_count:,} | {tier.size_mb:.1f} | "
            + " | ".join(times)
            + f" | **{best_w}w** |"
        )

    L += ["", "---", "", "## Raw Runs", ""]
    L += [
        "| Tier | Workers | Run | Elapsed (s) | MB/s | Files/s |",
        "|---|:---:|:---:|---:|---:|---:|",
    ]
    for tier in tiers:
        run_idx: Dict[int, int] = {w: 0 for w in worker_counts}
        for r in tier.results:
            for _ in range(runs):
                run_idx[r.workers] += 1
                break
            L.append(
                f"| `{tier.name}` | {r.workers} | {run_idx[r.workers]} | "
                f"{_fmt(r.elapsed_sec)} | {r.mb_per_sec:.2f} | {r.files_per_sec:.0f} |"
            )

    # Inference
    all_times: Dict[int, List[float]] = {w: [] for w in worker_counts}
    all_mbps:  Dict[int, List[float]] = {w: [] for w in worker_counts}
    for tier in tiers:
        for w in worker_counts:
            for r in tier.results_for(w):
                all_times[w].append(r.elapsed_sec)
                all_mbps[w].append(r.mb_per_sec)

    total_tested = sum(win_count.values())
    overall_best = max(worker_counts, key=lambda w: win_count[w])

    L += [
        "",
        "---",
        "",
        "## Inference",
        "",
        "### Win Rate",
        "",
        "| Workers | Tiers Won | Win % | Mean MB/s | Mean Time (s) |",
        "|:---:|---:|---:|---:|---:|",
    ]
    for w in worker_counts:
        pct    = win_count[w] / total_tested * 100 if total_tested else 0
        mbps   = statistics.mean(all_mbps[w])  if all_mbps[w]  else 0
        mean_t = statistics.mean(all_times[w]) if all_times[w] else 0
        L.append(
            f"| **{w}w** | {win_count[w]}/{total_tested} "
            f"| {pct:.0f}% | {mbps:.2f} | {mean_t:.2f} |"
        )

    L += [
        "",
        "### Scaling Behaviour",
        "",
        "| Tier | Files | "
        + " | ".join(f"{w}w (s)" for w in worker_counts)
        + " | Files/s (best) |",
        "|---|---:|"
        + "|".join("---:" for _ in worker_counts)
        + "|---:|",
    ]
    for tier in tiers:
        best_w = tier.fastest_workers(worker_counts)
        best_rs = tier.results_for(best_w)
        fps = statistics.mean(r.files_per_sec for r in best_rs) if best_rs else 0
        times = [_fmt(tier.mean_sec(w)) for w in worker_counts]
        L.append(
            f"| `{tier.name}` | {tier.file_count:,} | "
            + " | ".join(times)
            + f" | {fps:.0f} |"
        )

    L += [
        "",
        f"**Recommended workers:** {overall_best}  "
        f"(won {win_count[overall_best]}/{total_tested} tiers, "
        f"{win_count[overall_best]/total_tested*100:.0f}%)",
        "",
        "---",
        "",
        "_Report generated by `digiworld/utils/benchmark_scale_parallel_copy.py`  "
        "·  seed assets from `digiworld/utils/scale_test_assets/`_",
    ]

    return "\n".join(L)


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

def main() -> int:
    parser = argparse.ArgumentParser(
        description="Benchmark parallel file copy at scale (1K–100K files)."
    )
    parser.add_argument(
        "--output", default=str(SCRIPT_DIR / "parallel_copy_benchmark_report.md"),
        help="Destination Markdown file (default: parallel_copy_benchmark_report.md)",
    )
    parser.add_argument("--runs",    type=int, default=DEFAULT_RUNS)
    parser.add_argument("--workers", nargs="+", type=int, default=WORKER_COUNTS)
    args = parser.parse_args()

    worker_counts = sorted(set(args.workers))
    runs          = max(1, args.runs)

    print("=" * 60)
    print("  Parallel Copy Scale Benchmark")
    print("=" * 60)
    print(f"  Assets dir : {ASSETS_DIR}")
    print(f"  Workers    : {worker_counts}")
    print(f"  Runs       : {runs}")
    print(f"  Report     : {args.output}")
    print("=" * 60)

    tiers = discover_tiers(ASSETS_DIR)
    if not tiers:
        print(f"[ERROR] No tier directories found under {ASSETS_DIR}")
        return 1

    total_files = sum(t.file_count for t in tiers)
    total_ops   = len(tiers) * len(worker_counts) * runs
    print(f"\n  Tiers  : {len(tiers)}  ({', '.join(t.name for t in tiers)})")
    print(f"  Files  : {total_files:,}  |  Total copy ops: {total_ops}")

    run_benchmarks(tiers, worker_counts, runs)

    report = generate_report(tiers, worker_counts, runs)
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(report, encoding="utf-8")

    print(f"\n{'='*60}")
    print(f"  Report saved → {out}")
    print(f"{'='*60}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
